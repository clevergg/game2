export const FONT_CHARS: readonly string[] = Object.keys(G);

/** Кадр символа: заливка fill, обводка outline, поле 1 пиксель под обводку. */
export function glyphImage(ch: string, fill: number, outline: number): IndexedImage {
  const rows = G[ch];
  if (!rows) throw new RangeError(`Нет глифа для «${ch}»`);
  const gw = rows[0]?.length ?? 0;
  const img = createImage(gw + 2, rows.length + 2);
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] === "#") img.data[(y + 1) * img.w + (x + 1)] = fill;
    }
  });
  // Обводка по 8-соседству: у мелкого шрифта так читаемее на пёстром фоне
  const src = img.data.slice();
  for (let y = 0; y < img.h; y++) {
    for (let x = 0; x < img.w; x++) {
      if (src[y * img.w + x] !== 0) continue;
      let near = false;
      for (let dy = -1; dy <= 1 && !near; dy++) {
        for (let dx = -1; dx <= 1 && !near; dx++) {
          const nx = x + dx;
          const ny = y + dy;
          if (nx >= 0 && ny >= 0 && nx < img.w && ny < img.h && src[ny * img.w + nx] === fill) near = true;
        }
      }
      if (near) img.data[y * img.w + x] = outline;
    }
  }
  return img;
}

/** Имя кадра символа в атласе: код символа, чтобы не зависеть от кириллицы в ключах. */
export function glyphFrameName(style: string, ch: string): string {
  return `font_${style}_${(ch.codePointAt(0) ?? 0).toString(16)}`;
}
